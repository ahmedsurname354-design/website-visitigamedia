create table if not exists public.careers_jobs (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(title) between 1 and 160),
  department text not null default '',
  location text not null default '',
  employment_type text not null default 'Full-time',
  description text not null default '',
  qualifications text[] not null default '{}',
  responsibilities text[] not null default '{}',
  deadline date,
  status text not null default 'draft' check (status in ('draft', 'published', 'closed')),
  sort_order integer not null default 0,
  content_id jsonb not null default '{}'::jsonb,
  content_en jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.careers_submissions ( 
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  submission_type text not null check (submission_type in ('partnership', 'job_application')),
  job_id uuid references public.careers_jobs(id) on delete set null,
  message text not null,
  status text not null default 'new' check (status in ('new', 'contacted', 'completed', 'spam')),
  notes text not null default '',
  submission_key uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists careers_jobs_public_idx on public.careers_jobs (status, sort_order, created_at desc);
create index if not exists careers_submissions_status_idx on public.careers_submissions (status, created_at desc);
create index if not exists careers_submissions_rate_idx on public.careers_submissions (submission_key, created_at desc);
create index if not exists careers_submissions_email_rate_idx on public.careers_submissions (lower(email), created_at desc);

drop trigger if exists careers_jobs_set_updated_at on public.careers_jobs;
drop trigger if exists careers_submissions_set_updated_at on public.careers_submissions;
create trigger careers_jobs_set_updated_at before update on public.careers_jobs for each row execute function public.set_updated_at();
create trigger careers_submissions_set_updated_at before update on public.careers_submissions for each row execute function public.set_updated_at();

alter table public.careers_jobs enable row level security;
alter table public.careers_submissions enable row level security;
drop policy if exists "Public read published careers jobs" on public.careers_jobs;
drop policy if exists "Admins manage careers jobs" on public.careers_jobs;
drop policy if exists "Admins read careers submissions" on public.careers_submissions;
drop policy if exists "Admins update careers submissions" on public.careers_submissions;
drop policy if exists "Admins delete careers submissions" on public.careers_submissions;
create policy "Public read published careers jobs" on public.careers_jobs for select to anon, authenticated using (status = 'published' or public.is_admin());
create policy "Admins manage careers jobs" on public.careers_jobs for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admins read careers submissions" on public.careers_submissions for select to authenticated using (public.is_admin());
create policy "Admins update careers submissions" on public.careers_submissions for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admins delete careers submissions" on public.careers_submissions for delete to authenticated using (public.is_admin());

revoke all on public.careers_submissions from anon, authenticated;
grant select on public.careers_jobs to anon, authenticated;
grant select, insert, update, delete on public.careers_jobs to authenticated;
grant select, update, delete on public.careers_submissions to authenticated;

create or replace function public.submit_careers_submission(
  p_name text, p_email text, p_phone text, p_submission_type text,
  p_job_id uuid, p_message text, p_submission_key uuid, p_honeypot text default ''
) returns bigint language plpgsql security definer set search_path = public, pg_temp as $$
declare inserted_id bigint; normalized_email text := lower(trim(p_email));
begin
  if nullif(trim(coalesce(p_honeypot, '')), '') is not null or p_submission_key is null then
    raise exception using errcode = 'P0001', message = 'Submission rejected.';
  end if;
  if char_length(trim(p_name)) not between 2 and 120
    or char_length(normalized_email) not between 5 and 254
    or normalized_email !~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    or (nullif(trim(p_phone), '') is not null and char_length(trim(p_phone)) not between 7 and 30)
    or p_submission_type not in ('partnership', 'job_application')
    or char_length(trim(p_message)) not between 10 and 5000 then
    raise exception using errcode = 'P0001', message = 'Invalid Careers form data.';
  end if;
  if p_submission_type = 'job_application' and (p_job_id is null or not exists (select 1 from public.careers_jobs where id = p_job_id and status = 'published')) then
    raise exception using errcode = 'P0001', message = 'Selected job is not available.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('careers-email:' || normalized_email, 0));
  if (select count(*) from public.careers_submissions where created_at >= now() - interval '15 minutes' and (submission_key = p_submission_key or lower(email) = normalized_email)) >= 3 then
    raise exception using errcode = 'P0001', message = 'Rate limit exceeded. Try again later.';
  end if;
  insert into public.careers_submissions(name, email, phone, submission_type, job_id, message, submission_key)
  values (trim(p_name), normalized_email, nullif(trim(p_phone), ''), p_submission_type, p_job_id, trim(p_message), p_submission_key)
  returning id into inserted_id;
  return inserted_id;
end; $$;
revoke all on function public.submit_careers_submission(text,text,text,text,uuid,text,uuid,text) from public;
grant execute on function public.submit_careers_submission(text,text,text,text,uuid,text,uuid,text) to anon, authenticated;

